// Visibility/state fixtures verify shared presentation independently of progression tests.
const names=['HudPanel','HealthText','CoinsText','WeaponText','StageStatus','GoalText','ChargeText','ChargeFill'];
const fixedNames=['HudPanel','HealthText','CoinsText','WeaponText','StageStatus','GoalText'];
const artNames=['ArtHeart','ArtCoin','ArtWeaponIcon'];
const one=n=>harness.getObjects(n)[0];
const geometry=()=>fixedNames.map(n=>{const o=one(n);return [n,o.x,o.y,o.layer];});
const artGeometry=()=>artNames.map(n=>{const o=one(n);return [n,o.x,o.y,o.width,o.height,o.layer];});
const assertHudSpacing=scene=>{
  const coin=one('ArtCoin'),health=one('ArtHeart'),weapon=one('ArtWeaponIcon');
  harness.assert(one('CoinsText').x>=coin.x+coin.width+4,scene+' coin number has a real gap from its icon');
  harness.assert(one('HealthText').x>=health.x+health.width+4,scene+' health number has a real gap from its icon');
  harness.assert(one('WeaponText').x>=weapon.x+weapon.width+4,scene+' weapon text has a real gap from its icon');
  harness.assert(artNames.every(n=>{const o=one(n);return o.x>=one('HudPanel').x&&o.x+o.width<=one('HudPanel').x+one('HudPanel').width&&o.y>=one('HudPanel').y&&o.y+o.height<=one('HudPanel').y+one('HudPanel').height;}),scene+' HUD art stays inside the compact panel');
};
await harness.goToScene('TrainingRoom');await harness.stepFrames(4);
harness.assert(names.every(n=>harness.getObjects(n).length===1),'training owns exactly one instance of every shared HUD object');
harness.assert(artNames.every(n=>harness.getObjects(n).length===1),'training owns exactly one rendered icon for every HUD value');
harness.assert(one('HudPanel').width<=304&&one('HudPanel').height<=80,'shared status bar is compact and anchored to the corner');
const trainingGeometry=JSON.stringify(geometry());
const trainingArtGeometry=JSON.stringify(artGeometry());
assertHudSpacing('training');
harness.assert(!one('KeyHelp').hidden&&!one('GoalText').hidden,'jump teaching shows lesson and controls');
await harness.takeScreenshot('Shared HUD in teaching stage');
harness.setSceneVariable('Stage','Combat');await harness.stepFrames(2);
harness.assert(one('KeyHelp').hidden,'leaving teaching hides the navigation key help');
harness.assert(one('GoalText').hidden,'leaving teaching hides the goal overlay');
harness.assert(one('PromptText').hidden,'leaving teaching hides contextual tutorial prompts');
await harness.goToScene('RescueBase');await harness.stepFrames(4);
harness.assert(names.every(n=>harness.getObjects(n).length===1),'base owns exactly one instance of every shared HUD object');
harness.assert(artNames.every(n=>harness.getObjects(n).length===1),'base owns exactly one rendered icon for every HUD value');
harness.assert(JSON.stringify(geometry())===trainingGeometry,'both scenes use identical shared HUD layout and layer');
harness.assert(JSON.stringify(artGeometry())===trainingArtGeometry,'both scenes use identical HUD icon geometry and layering');
assertHudSpacing('base');
harness.assert(one('KeyHelp').hidden&&one('GoalText').hidden&&one('PromptText').hidden,'base has no navigation or jump tutorial');
harness.setSceneVariable('Health',2);harness.setSceneVariable('Coins',37);await harness.stepFrames(2);
harness.assert(one('HealthText').text==='2/3'&&one('CoinsText').text==='37','shared presenter reads the active scene health and wallet');
harness.setSceneVariable('HasCannon',true);harness.setSceneVariable('CurrentWeapon','Cannon');
harness.setKeyPressed('w',true);await harness.stepFrames(50);
harness.assert(one('WeaponText').text.includes('穿盾炮')&&one('ChargeText').hidden,'weapon appears in the status bar without a separate charge label');
harness.assert(!one('ChargeFill').hidden&&one('ChargeFill').width===32&&one('ChargeFill').height<=5&&one('ChargeFill').layer==='Gameplay','charged weapon uses a visible tiny in-world meter');
harness.assert(Math.abs(one('ChargeFill').x-(one('Player').x+4))<0.1&&one('ChargeFill').y>=one('Player').y+56,'charge meter follows beneath the character');
harness.assert(one('KeyHelp').hidden&&one('PromptText').hidden,'charging never restores tutorial overlays in base');
await harness.takeScreenshot('Shared compact HUD in rescue base');
harness.releaseAllInputs();
await harness.stepFrames(1);
harness.assert(one('ChargeFill').hidden,'releasing the shot hides the charge meter');
await harness.stepFrames(42);harness.setKeyPressed('w',true);await harness.stepFrames(8);
harness.assert(!one('ChargeFill').hidden&&one('ChargeFill').width<32,'partial charge displays proportional progress');
harness.setKeyPressed('q',true);await harness.stepFrames(1);
harness.assert(one('ChargeFill').hidden,'switching to the energy gun hides the meter');
harness.releaseAllInputs();
