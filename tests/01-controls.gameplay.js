await harness.goToScene('TrainingRoom');
const probes=await harness.resetSceneAndProbeControls('Player',['Left','Right','Space'],{frames:12});
console.log('Native platformer control map: '+JSON.stringify(probes));
harness.assert(probes.keys.Left.dx<probes.baseline.dx-20,'left arrow moves left');
harness.assert(probes.keys.Right.dx>probes.baseline.dx+20,'right arrow moves right');
harness.assert(probes.keys.Space.minDy<probes.baseline.minDy-60,'space moves upward through the native platformer');
await harness.goToScene('TrainingRoom');await harness.stepFrames(4);
harness.assert(harness.getSceneVariable('GameMode').value==='Playing','starts playing without online services');
harness.assert(harness.getSceneVariable('Stage').value==='Jump','starts with jump guidance');
harness.assert(harness.getObjects('Player')[0].width===40&&harness.getObjects('Player')[0].height===56,'player has a 40 by 56 native collider');
let minJumpY=harness.getObjects('Player')[0].y;
harness.setKeyPressed('Space',true);await harness.stepFrames(60,{onFrame:()=>{minJumpY=Math.min(minJumpY,harness.getObjects('Player')[0].y);}});
harness.assert(minJumpY>=350&&minJumpY<=368,'native jump reaches approximately 144 pixels above the floor');
harness.assert(harness.getSceneVariable('Jumps').value===1,'holding space triggers only one jump');
harness.assert(harness.getSceneVariable('DoubleJumps').value===0,'holding space never consumes an air jump');
harness.releaseAllInputs();await harness.stepFrames(3);
harness.setKeyPressed('Space',true);await harness.stepFrames(12);
harness.setKeyPressed('Space',false);await harness.stepFrames(2);
harness.setKeyPressed('Space',true);await harness.stepFrames(3);
harness.assert(harness.getSceneVariable('JumpCount').value===2,'a second press consumes the air jump');
harness.assert(harness.getSceneVariable('DoubleJumps').value===1,'actual air jump is recorded');
harness.setKeyPressed('Space',false);await harness.stepFrames(2);
harness.setKeyPressed('Space',true);await harness.stepFrames(3);
harness.assert(harness.getSceneVariable('Jumps').value===3,'third airborne press cannot add another jump');
harness.releaseAllInputs();await harness.stepFrames(90);
harness.assert(harness.getSceneVariable('JumpCount').value===0,'landing restores both jump opportunities');
harness.setKeyPressed('q',true);await harness.stepFrames(2);harness.releaseAllInputs();
harness.assert(harness.getSceneVariable('WeaponForm').value==='Base','cannot equip an unpurchased upgrade');
