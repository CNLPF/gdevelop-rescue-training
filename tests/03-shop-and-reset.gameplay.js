await harness.goToScene('TrainingRoom');await harness.stepFrames(4);
const p=()=>harness.getObjects('Player')[0];
const value=n=>harness.getSceneVariable(n).value;
const tap=async key=>{harness.setKeyPressed(key,true);await harness.stepFrames(1);harness.setKeyPressed(key,false);await harness.stepFrames(1);};
// Set up purchase boundaries without claiming that the walkthrough was completed.
harness.setSceneVariable('Stage','Purchase');harness.setSceneVariable('Coins',9);
harness.setObjectPosition(p().id,1930,504);await harness.stepFrames(3);
await tap('e');harness.assert(value('GameMode')==='Shop','E opens shop at close range');
const before={x:p().x,y:p().y,patrol:harness.getObjects('Patrol')[0].x,jumps:value('Jumps'),shots:value('ShotsFired')};
harness.setKeyPressed('Right',true);harness.setKeyPressed('Space',true);harness.setKeyPressed('w',true);await harness.stepFrames(90);harness.releaseAllInputs();
harness.assert(p().x===before.x&&p().y===before.y,'shop freezes player physics');
harness.assert(harness.getObjects('Patrol')[0].x===before.patrol,'shop freezes enemies');
harness.assert(value('Jumps')===before.jumps&&value('ShotsFired')===before.shots,'shop suppresses gameplay input');
await tap('Return');
harness.assert(value('Coins')===9&&!value('UpgradePurchased'),'nine coins rejects purchase without deduction');
harness.setSceneVariable('Coins',10);await tap('Return');
harness.assert(value('Coins')===0&&value('UpgradePurchased'),'ten coins purchases once and leaves zero');
harness.assert(value('Purchases')===1&&value('WeaponForm')==='Upgrade','purchase equips the upgrade and records the action');
await tap('Return');harness.assert(value('Coins')===0&&value('Purchases')===1,'repeated confirmation cannot charge again');
await harness.takeScreenshot('Keyboard shop after purchase');
await tap('Escape');
harness.assert(value('GameMode')==='Playing'&&value('Stage')==='Compare','shop closes and unlocks comparison stage');
await tap('q');harness.assert(value('WeaponForm')==='Base','Q switches back to base form');
await tap('q');harness.assert(value('WeaponForm')==='Upgrade','Q equips purchased upgrade again');
harness.setSceneVariable('Coins',4);
const patrol=harness.getObjects('Patrol')[0];harness.setObjectVariable(patrol.id,'Health',1);
harness.setSceneVariable('Health',0);await harness.stepFrames(6);
harness.assert(value('Retries')===0&&value('Health')===3&&value('GameMode')==='Playing','death starts a fresh game at full health');
harness.assert(value('Coins')===4&&!value('UpgradePurchased')&&value('Stage')==='Jump','new game retains wallet but resets purchase and stage');
harness.assert(value('WeaponForm')==='Base'&&value('Purchases')===0,'new game resets weapon and current-run record');
harness.assert(harness.getObjectVariable('Patrol','Health').value===2,'new game restores enemies');
harness.assert(harness.getObjects('Bullet').length===0&&harness.getObjects('EnemyBullet').length===0,'new game has no old projectiles');
await tap('r');harness.assert(value('GameMode')==='RestartConfirm','R requires explicit confirmation');
await tap('Escape');harness.assert(value('Coins')===4&&value('Stage')==='Jump','cancel restart retains progress');
// Falls keep the room intact; an explicitly confirmed new run resets it.
const retryPatrol=harness.getObjects('Patrol')[0];harness.setObjectVariable(retryPatrol.id,'Health',1);
harness.setObjectPosition(p().id,80,740);await harness.stepFrames(35);
harness.assert(harness.getObjectVariable('Patrol','Health').value===1,'fall retains living enemy damaged health');
await tap('r');await tap('Return');await harness.stepFrames(4);
harness.assert(value('Stage')==='Jump'&&value('Coins')===4&&!value('UpgradePurchased'),'confirmed restart restores progression while keeping wallet');
harness.assert(value('Retries')===0&&value('Purchases')===0&&value('Hits')===0,'restart clears interaction record');
harness.assert(harness.getObjects('Coin').length===8&&harness.getObjects('Patrol').length===1&&harness.getObjects('Turret').length===1,'restart restores all pickups and enemies');
