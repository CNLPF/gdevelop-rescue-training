// The acceptance walkthrough uses only keyboard inputs: no spawned objects, teleports or state edits.
await harness.goToScene('TrainingRoom');await harness.stepFrames(4);
harness.watch('Player');
const p=()=>harness.getObjects('Player')[0];
const value=n=>harness.getSceneVariable(n).value;
const onFloor=()=>harness.getRuntimeObject('Player').getBehavior('Platformer').isOnFloor();
const tap=async key=>{harness.setKeyPressed(key,true);await harness.stepFrames(1);harness.setKeyPressed(key,false);await harness.stepFrames(1);};
async function walkTo(x,max=180){
  const direction=p().x<x?'Right':'Left';harness.setKeyPressed(direction,true);
  const reached=await harness.stepUntil(()=>direction==='Right'?p().x>=x:p().x<=x,{maxFrames:max});
  harness.setKeyPressed(direction,false);await harness.stepFrames(6);
  harness.assert(reached,'keyboard reaches x='+x+'; actual='+p().x+', y='+p().y+', stage='+value('Stage'));
}
await walkTo(165);
harness.setKeyPressed('Right',true);await tap('Space');
await harness.stepUntil(()=>p().x>=270,{maxFrames:80});harness.setKeyPressed('Right',false);
await harness.stepFrames(55);
harness.assert(onFloor()&&p().y<450,'first jump lands on the low practice step');
harness.setKeyPressed('Right',true);await tap('Space');await harness.stepFrames(16);await tap('Space');
console.log('high jump starts '+JSON.stringify({x:p().x,y:p().y,jumps:value('Jumps')}));
const reachedBeacon=await harness.stepUntil(()=>value('Stage')==='Combat',{maxFrames:130,onFrame:({frame})=>{if(frame%15===0)console.log('jump trace '+JSON.stringify({x:p().x,y:p().y,stage:value('Stage'),mode:value('GameMode')}));}});harness.releaseAllInputs();await harness.stepFrames(30);
harness.assert(reachedBeacon,'double jump reaches the high beacon and opens combat');
harness.assert(value('DoubleJumps')>=1,'guidance progression follows a real double jump');
await walkTo(490);await walkTo(600);
harness.assert(value('Coins')>=4,'collects four reachable map coins before battle');
await harness.takeScreenshot('Double jump practice completed');

harness.setKeyPressed('Right',true);await tap('Space');await harness.stepFrames(16);await tap('Space');
const crossed=await harness.stepUntil(()=>p().x>=970,{maxFrames:160});harness.releaseAllInputs();await harness.stepFrames(60);
harness.assert(crossed,'double jump crosses practice pit into combat');
harness.setKeyPressed('w',true);await walkTo(1050);
const patrolDown=await harness.stepUntil(()=>!harness.getObjects('Patrol').length,{maxFrames:180});
harness.assert(patrolDown,'base gun defeats patrol through actual keyboard shots');
await walkTo(1260);await walkTo(1380);
harness.setKeyPressed('Right',true);await tap('Space');
const pastCover=await harness.stepUntil(()=>p().x>=1530,{maxFrames:100});harness.setKeyPressed('Right',false);
harness.assert(pastCover,'jump passes the real projectile-blocking cover');
const turretDown=await harness.stepUntil(()=>!harness.getObjects('Turret').length,{maxFrames:240});harness.setKeyPressed('w',false);
harness.assert(turretDown,'base gun defeats the warning turret');
await harness.stepFrames(25);await walkTo(1690);
harness.assert(value('EnemiesDefeated')===2&&value('Coins')>=10,'actual combat and pickups fund the upgrade');
harness.assert(value('Stage')==='Purchase','combat gate opens after both conditions are met');
await walkTo(1930);await tap('e');
harness.assert(value('GameMode')==='Shop','walkthrough opens the keyboard shop');
const earned=value('Coins');await tap('Return');
harness.assert(value('Coins')===earned-10&&value('Purchases')===1,'walkthrough buys one upgrade with earned coins');
await harness.takeScreenshot('Actual earned coins purchase');
await tap('Escape');
harness.assert(value('Stage')==='Compare','closing shop opens comparison area');
await walkTo(2370);await tap('q');
harness.assert(value('WeaponForm')==='Base','walkthrough can compare the base form');
await tap('q');harness.setKeyPressed('w',true);
const targetDown=await harness.stepUntil(()=>value('Stage')==='Finish',{maxFrames:120});harness.releaseAllInputs();
harness.assert(targetDown&&value('DummyHits')===2,'two real upgraded hits destroy the training target');
await tap('e');
harness.assert(value('DummyHealth')===4&&value('Stage')==='Finish','resetting dummy does not close an already unlocked exit');
harness.setKeyPressed('Right',true);
const finished=await harness.stepUntil(()=>value('GameMode')==='Complete',{maxFrames:240});harness.releaseAllInputs();
harness.assert(finished&&value('Completed'),'keyboard walkthrough reaches the rescue exit');
harness.assert(harness.getRuntimeLayer('Modal').isVisible(),'completion record is visible');
harness.assert(value('StageAdvanceCount')===4,'guided progression advances exactly four times');
harness.assert(value('Hits')>=8&&value('CoinsCollected')>=10&&value('Purchases')===1,'record is backed by actual pickups, hits and purchases');
await harness.takeScreenshot('Rescue complete with actual interaction record');
console.log(JSON.stringify({coinsCollected:value('CoinsCollected'),wallet:value('Coins'),hits:value('Hits'),retries:value('Retries'),purchases:value('Purchases'),doubleJumps:value('DoubleJumps')}));
